  const LANGS = Object.keys(T);
  const STORAGE_KEY = "route-tracker-lang";

  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGS.includes(saved)) return saved;
    } catch (e) { /* ignora */ }
    const browser = (navigator.language || "pt").slice(0, 2).toLowerCase();
    return LANGS.includes(browser) ? browser : "pt";
  }

  let lang = detect();

  function t(key, vars) {
    let s = (T[lang] && T[lang][key]) || T.pt[key] || key;
    if (vars) Object.keys(vars).forEach((k) => { s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]); });
    return s;
  }

  // Static markup: [data-i18n] -> textContent, [data-i18n-title] -> title,
  // [data-i18n-placeholder] -> placeholder. Dynamic strings go through t().
  function applyStatic() {
    document.documentElement.lang = { pt: "pt-PT", en: "en", fr: "fr", de: "de", it: "it" }[lang] || lang;
    document.title = t("appTitle");
    document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.getAttribute("data-i18n-title")); });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.getAttribute("data-i18n-placeholder")); });
    const sel = document.getElementById("langSelect");
    if (sel) sel.value = lang;
  }

